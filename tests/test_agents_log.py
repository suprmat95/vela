def line(obj):
    return json.dumps(obj)


def user(content, ts, **extra):
    d = {"type": "user", "isSidechain": False, "timestamp": ts,
         "message": {"role": "user", "content": content}, "sessionId": SESSION}
    d.update(extra)
    return line(d)


def assistant(blocks, ts, **extra):
    d = {"type": "assistant", "isSidechain": False, "timestamp": ts,
         "message": {"role": "assistant", "content": blocks}, "sessionId": SESSION}
    d.update(extra)
    return line(d)


