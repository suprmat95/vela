class IsGitCommitTest(unittest.TestCase):
    def test_plain_commit(self):
        self.assertTrue(agents_log.is_git_commit("git commit -m 'x'"))

    def test_status_is_not_commit(self):
        self.assertFalse(agents_log.is_git_commit("git status"))

    def test_chained_commit(self):
        self.assertTrue(agents_log.is_git_commit("git add . && git commit -m x"))

    def test_word_commit_without_git(self):
        self.assertFalse(agents_log.is_git_commit("echo commit"))


class ParseTranscriptTest(unittest.TestCase):
    def setUp(self):
        self.entries, self.meta = agents_log.parse_transcript(FIXTURE)

    def test_keeps_user_and_assistant_text(self):
        kinds = [(e.role, e.text) for e in self.entries if e.role != "tool"]
        self.assertEqual(kinds, [
            ("user", "Obiettivo: trascrivere le chat con gli agenti"),
            ("assistant", "Comincio."),
            ("user", "Grazie, procedi."),
            ("assistant", "Fatto."),
        ])

    def test_one_tool_entry_per_tool_use(self):
        tools = [e.text for e in self.entries if e.role == "tool"]
        self.assertEqual(tools, ["Bash: List files", "Edit /repo/src/app.py"])

    def test_discards_noise(self):
        blob = "\n".join(e.text for e in self.entries)
        for noise in ("local-command-caveat", "/clear", "secret thoughts", "file list output",
                      "Base directory", "subagent chatter", "hidden", "system-reminder"):
            self.assertNotIn(noise, blob)

    def test_meta(self):
        self.assertEqual(self.meta["title"], "Trascrizione chat agenti")
        self.assertEqual(self.meta["session_id"], SESSION)

    def test_timestamps_are_aware_datetimes(self):
        self.assertEqual(self.entries[0].ts, datetime(2026, 9, 24, 21, 10, 48, 356000, tzinfo=timezone.utc))


class ToolLabelTest(unittest.TestCase):
    def test_bash_prefers_description(self):
        self.assertEqual(agents_log.tool_label("Bash", {"command": "rm x", "description": "Remove x"}), "Bash: Remove x")

    def test_bash_without_description_truncates_command(self):
        label = agents_log.tool_label("Bash", {"command": "x" * 200})
        self.assertTrue(label.startswith("Bash: " + "x" * 80))
        self.assertTrue(label.endswith("…"))
        self.assertLessEqual(len(label), 6 + 81)

    def test_file_tools_use_path(self):
        self.assertEqual(agents_log.tool_label("Read", {"file_path": "/a/b.py"}), "Read /a/b.py")

    def test_skill_and_agent(self):
        self.assertEqual(agents_log.tool_label("Skill", {"skill": "foo:bar"}), "Skill foo:bar")
        self.assertEqual(agents_log.tool_label("Agent", {"description": "Search repo", "prompt": "..."}), "Agent: Search repo")

    def test_unknown_tool_is_name_only(self):
        self.assertEqual(agents_log.tool_label("Whatever", {"x": 1}), "Whatever")


class SessionFilenameTest(unittest.TestCase):
    def test_uses_local_time_and_slug(self):
        entries, _ = agents_log.parse_transcript(FIXTURE)
        name = agents_log.session_filename(entries)
        first = entries[0].ts.astimezone()
        self.assertEqual(name, first.strftime("%Y-%m-%d-%H%M") + "-obiettivo-trascrivere-le-chat-con-gli-ag.md")

    def test_slug_is_ascii_and_bounded(self):
        self.assertEqual(agents_log.slugify("Perché è così?! Àccènti & simboli"), "perche-e-cosi-accenti-simboli")
        self.assertEqual(len(agents_log.slugify("a " * 100)), 40 - 1)  # trailing dash trimmed

    def test_empty_slug_falls_back_to_session(self):
        entries, _ = agents_log.parse_transcript(FIXTURE)
        self.assertEqual(agents_log.session_filename([], session_id="abc12345-x"), None)


